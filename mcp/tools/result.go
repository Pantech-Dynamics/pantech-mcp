// errNoCredentials is returned when a call has no API key to use.
var errNoCredentials = errors.New("no credentials")

// ErrNoCredentials is the error Env.Client returns when there is no key.
var ErrNoCredentials = errNoCredentials

// userError is an error whose message is ours and safe to show as is.
type userError struct{ msg string }

func (e *userError) Error() string { return e.msg }

func errorf(format string, args ...any) error { return &userError{fmt.Sprintf(format, args...)} }

// toolError maps any error to a tool error result. API errors show the API's
// own title, detail and request id (they are written to be shown); anything
// else gets a generic message, so no internal detail leaks.
func toolError(ctx context.Context, err error) *Result {
	rec := record(ctx)
	var ue *userError
	var opErr *pantech.OperationError
	var orderErr *pantech.OrderError
	switch {
	case errors.As(err, &ue):
		return &Result{IsError: true, Text: ue.msg}
	case errors.Is(err, errNoCredentials):
		return &Result{IsError: true, Text: "No Pantech credentials for this call. Run `pantech auth login` or set PANTECH_API_KEY, or reconnect this AI app."}
	case errors.As(err, &opErr):
		op := opErr.Operation
		text := fmt.Sprintf("Operation %s (%s) failed.", op.ID, op.Kind)
		if op.Failure != nil {
			text = fmt.Sprintf("Operation %s (%s) failed: %s (%s).", op.ID, op.Kind, op.Failure.Reason, op.Failure.Code)
			rec.Code = op.Failure.Code
		}
		return &Result{IsError: true, Text: text, Data: map[string]any{"operation": op}}
	case errors.As(err, &orderErr):
		text := fmt.Sprintf("The %s order %s ended as %s", orderErr.Kind, orderErr.OrderID, orderErr.Status)
		if orderErr.FailureCode != "" {
			text += " (" + orderErr.FailureCode + ")"
		}
		text += ": nothing was provisioned, and any payment taken is returned to your credit."
		rec.Code = orderErr.FailureCode
		return &Result{IsError: true, Text: text}
	}
	if e, isAPI := pantech.AsError(err); isAPI {
		rec.Code, rec.APIRequestID = e.Code, e.RequestID
		var b strings.Builder
		title := e.Title
		if title == "" {
			title = fmt.Sprintf("Request failed (status %d)", e.Status)
		}
		b.WriteString("Error: " + title)
		if e.Detail != "" && e.Detail != e.Title {
			b.WriteString(": " + e.Detail)
		}
		for _, fe := range e.Errors {
			msg := fe.Message
			if msg == "" {
				msg = fe.Code
			}
			fmt.Fprintf(&b, "\n- %s: %s", fe.Field, msg)
		}
		if e.RequestID != "" {
			b.WriteString("\nRequest id (quote it to support): " + e.RequestID)
		}
		if h, ok := hints[e.Code]; ok {
			b.WriteString("\n" + h)
		}
		data := map[string]any{"status": e.Status, "code": e.Code, "title": e.Title, "detail": e.Detail, "request_id": e.RequestID}
		if len(e.Errors) > 0 {
			data["fields"] = e.Errors
		}
		return &Result{IsError: true, Text: b.String(), Data: map[string]any{"error": data}}
	}
	if errors.Is(err, context.DeadlineExceeded) || errors.Is(err, context.Canceled) {
		rec.Code = "TIMEOUT"
		return &Result{IsError: true, Text: "The request took too long and was stopped. If it was a change, check with the matching list or get tool before trying again."}
	}
	rec.Code = "NETWORK"
	return &Result{IsError: true, Text: "Could not reach the Pantech API. Try again in a moment."}
}

// exactAmounts is the guidance every tool that reports money gives the model.
const exactAmounts = "All amounts are exact minor-unit values converted to the currency's major unit; report them exactly as given, never rounded or approximated."

// currencyDigits is how many minor-unit digits each billing currency has:
// kobo for NGN, cents for USD.
var currencyDigits = map[string]int{"NGN": 2, "USD": 2}

// minorDigits is how many minor-unit digits a currency has (two for a code
// Pantech does not bill in).
func minorDigits(currency string) int {
	if d, ok := currencyDigits[currency]; ok {
		return d
	}
	return 2
}

// money formats an exact amount in minor units: 1250000 NGN → "NGN 12,500.00".
// It uses integer arithmetic only, so nothing is rounded.
func money(minor int64, currency string) string {
	neg := minor < 0
	// Work in uint64 so the smallest int64 still negates exactly.
	u := uint64(minor)
	if neg {
		u = uint64(-(minor + 1)) + 1
	}
	digits := minorDigits(currency)
	scale := uint64(1)
	for range digits {
		scale *= 10
	}
	whole, frac := u/scale, u%scale
	s := strconv.FormatUint(whole, 10)
	var b strings.Builder
	for i, ch := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			b.WriteByte(',')
		}
		b.WriteRune(ch)
	}
	sign := ""
	if neg {
		sign = "-"
	}
	out := fmt.Sprintf("%s%s %s", sign, currency, b.String())
	if digits > 0 {
		out += fmt.Sprintf(".%0*d", digits, frac)
	}
	return out
}

// redactURL keeps a webhook URL's scheme, host and path and drops anything
// that could be a secret: user info, query and fragment.
func redactURL(raw string) string {
	u, err := url.Parse(raw)
	if err != nil || u.Host == "" {
		return "(hidden)"
	}
	out := u.Scheme + "://" + u.Host + u.EscapedPath()
	if u.RawQuery != "" || u.User != nil || u.Fragment != "" {
		out += " (query and credentials hidden)"
	}
	return out
}

func str(p *string) string {
	if p == nil {
		return ""
	}
	return *p
}

func plural(n int, one, many string) string {
	if n == 1 {
		return "1 " + one
	}
	return fmt.Sprintf("%d %s", n, many)
}
