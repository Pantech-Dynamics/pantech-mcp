type databaseInput struct {
	DatabaseID string `json:"database_id" jsonschema:"The database's id, e.g. db_…"`
}

// No password field: the server never lets a password pass through the
// conversation. The API generates one, which this tool does not return; the
// user sets their own in the console.
type createDatabaseInput struct {
	Name          string   `json:"name" jsonschema:"1 to 255 characters, unique among your databases."`
	Engine        string   `json:"engine" jsonschema:"postgresql, mysql or mariadb."`
	Version       string   `json:"version" jsonschema:"A version line offered for the engine in the zone, e.g. 18 for PostgreSQL or 8.4 for MySQL."`
	PlanSlug      string   `json:"plan_slug" jsonschema:"The size, from list_plans."`
	ZoneID        string   `json:"zone_id" jsonschema:"The zone, e.g. af-abj-1 (standard) or af-abj-2 (VPC)."`
	SubnetID      string   `json:"subnet_id,omitempty" jsonschema:"Required in a VPC zone: one of your subnets there."`
	AccessRules   []string `json:"access_rules,omitempty" jsonschema:"The initial allow-list: IPv4 CIDRs with a prefix of /8 or longer, never 0.0.0.0/0."`
	AdminUsername string   `json:"admin_username,omitempty" jsonschema:"The admin login's name: 3 to 32 lowercase letters, digits and underscores, starting with a letter."`
	StorageGB     int      `json:"storage_gb,omitempty" jsonschema:"Data disk size in GB."`
	Confirmation
}

type updateDatabaseAccessRulesInput struct {
	DatabaseID string   `json:"database_id" jsonschema:"The database's id."`
	CIDRs      []string `json:"cidrs" jsonschema:"The COMPLETE new allow-list of IPv4 CIDRs (prefix /8 or longer, never 0.0.0.0/0). It replaces every current rule; [] removes them all."`
	Confirmation
}

func init() {
	add(Spec{
		Name: "list_databases", Title: "List databases",
		Description: "List the organization's managed databases (PostgreSQL, MySQL, MariaDB) with their engine, version, hostname and state.",
		Risk:        Read, Idempotent: true,
		Routes: []string{"GET /databases"},
	}, func(ctx context.Context, c *Call, in listInput) (*Result, error) {
		page, err := c.Client.Databases.List(ctx, in.params())
		if err != nil {
			return nil, err
		}
		return pageResult(page, "database", "databases")
	})

	add(Spec{
		Name: "get_database", Title: "Get a database",
		Description: "Get one managed database: engine, version, hostname, port, storage, access rules and state. Never returns passwords.",
		Risk:        Read, Idempotent: true,
		Routes: []string{"GET /databases/{database_id}"},
	}, func(ctx context.Context, c *Call, in databaseInput) (*Result, error) {
		if err := checkIDs("database_id", in.DatabaseID); err != nil {
			return nil, err
		}
		db, err := c.Client.Databases.Get(ctx, in.DatabaseID)
		if err != nil {
			return nil, err
		}
		return ok(fmt.Sprintf("Database %s (%s %s) is %s.", db.ID, db.Engine, db.Version, db.ObservedState), db)
	})

	addConfirmed(Spec{
		Name: "create_database", Title: "Create a database",
		Description: "Create a single-node managed PostgreSQL, MySQL or MariaDB database. Paid first like an instance. The admin password is generated and is NOT returned here: the user sets or resets it in the console.",
		Risk:        Cost,
		Routes:      []string{"GET /plans", "GET /billing/credit", "POST /databases", "GET /database-orders/{order_id}", "GET /operations/{operation_id}"},
	}, func(ctx context.Context, c *Call, in createDatabaseInput) (*Preview, error) {
		placement := placementOf(in.SubnetID, "")
		plan, err := c.findPlan(ctx, in.PlanSlug, placement)
		if err != nil {
			return nil, err
		}
		p := &Preview{
			Action:   fmt.Sprintf("Create a %s %s database on plan %s (%d vCPU, %d MB memory) in zone %s.", arg(in.Engine), arg(in.Version), plan.Slug, plan.VCPU, plan.MemoryMB, arg(in.ZoneID)),
			Price:    planPrice(plan) + " (storage beyond the plan's disk is extra)",
			Warnings: []string{"The admin password is generated by Pantech and not shown here; the user sets their own in the console (Databases › the database › Reset password)."},
			Data:     map[string]any{"request": in.request(), "plan": plan},
		}
		if note := c.creditNote(ctx); note != "" {
			p.Warnings = append(p.Warnings, note)
		}
		return p, nil
	}, func(ctx context.Context, c *Call, in createDatabaseInput) (*Result, error) {
		// Decode only what is safe: a generated password in the response is dropped here.
		var order struct {
			OrderID    string `json:"order_id"`
			DatabaseID string `json:"database_id"`
		}
		if err := c.Client.Do(ctx, "POST", "/databases", nil, in.request(), &order, c.writeOpts()...); err != nil {
			return nil, err
		}
		res, err := c.followOrder(ctx, "database", order.OrderID, order.DatabaseID, func(ctx context.Context) (string, *string, *string, error) {
			o, err := c.Client.Databases.GetOrder(ctx, order.OrderID)
			if err != nil {
				return "", nil, nil, err
			}
			return o.Status, o.OperationID, o.FailureCode, nil
		})
		if res != nil {
			res.Text += " The admin password is not shown here: set one in the console."
		}
		return res, err
	})

	addConfirmed(Spec{
		Name: "update_database_access_rules", Title: "Replace a database's access rules",
		Description: "Replace a database's whole allow-list of IPv4 ranges. Removing a range also ends connections already open from it. Get the current rules with get_database first.",
		Risk:        Destructive, Destructive: true, Idempotent: true,
		Routes: []string{"GET /databases/{database_id}", "PUT /databases/{database_id}/access-rules", "GET /operations/{operation_id}"},
	}, func(ctx context.Context, c *Call, in updateDatabaseAccessRulesInput) (*Preview, error) {
		if err := checkIDs("database_id", in.DatabaseID); err != nil {
			return nil, err
		}
		db, err := c.Client.Databases.Get(ctx, in.DatabaseID)
		if err != nil {
			return nil, err
		}
		var current []string
		for _, r := range db.AccessRules {
			current = append(current, r.CIDR)
		}
		added, removed := diffStrings(current, in.CIDRs)
		p := &Preview{
			Action: fmt.Sprintf("Replace the allow-list of database %s (%s) with %s: %d added, %d removed.",
				db.ID, plural(len(current), "range now", "ranges now"), plural(len(in.CIDRs), "range", "ranges"), len(added), len(removed)),
			Data: map[string]any{"current": current, "new": in.CIDRs, "added": added, "removed": removed},
		}
		if len(removed) > 0 {
			p.Warnings = append(p.Warnings, "Connections already open from removed ranges are ended.")
		}
		return p, nil
	}, func(ctx context.Context, c *Call, in updateDatabaseAccessRulesInput) (*Result, error) {
		rules := make([]pantech.DatabaseAccessRuleRequest, 0, len(in.CIDRs))
		for _, cidr := range in.CIDRs {
			rules = append(rules, pantech.DatabaseAccessRuleRequest{CIDR: cidr})
		}
		acc, err := c.Client.Databases.ReplaceAccessRules(ctx, in.DatabaseID, pantech.ReplaceDatabaseAccessRulesRequest{Rules: rules}, c.writeOpts()...)
		if err != nil {
			return nil, err
		}
		return c.finish(ctx, acc, "database "+in.DatabaseID+" access rules replaced")
	})
}

func (in createDatabaseInput) request() pantech.CreateDatabaseRequest {
	req := pantech.CreateDatabaseRequest{Name: in.Name, Engine: in.Engine, Version: in.Version, PlanSlug: in.PlanSlug, ZoneID: in.ZoneID}
	if in.SubnetID != "" {
		req.SubnetID = pantech.Ptr(in.SubnetID)
	}
	if len(in.AccessRules) > 0 {
		req.AccessRules = &in.AccessRules
	}
	if in.AdminUsername != "" {
		req.AdminUsername = pantech.Ptr(in.AdminUsername)
	}
	if in.StorageGB > 0 {
		req.StorageGB = pantech.Ptr(in.StorageGB)
	}
	return req
}

func diffStrings(current, next []string) (added, removed []string) {
	has := func(list []string, s string) bool {
		for _, x := range list {
			if x == s {
				return true
			}
		}
		return false
	}
	for _, s := range next {
		if !has(current, s) {
			added = append(added, s)
		}
	}
	for _, s := range current {
		if !has(next, s) {
			removed = append(removed, s)
		}
	}
	return added, removed
}

